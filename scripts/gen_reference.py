def _count_leaves(node: object) -> int:
    if isinstance(node, dict):
        return sum(_count_leaves(value) for value in node.values())
    return 1


def count_i18n_keys(text: str, source: str) -> tuple[int, int]:
    """(total leaf keys excluding _meta, leaf keys under web)."""
    data = yaml.safe_load(text)
    if not isinstance(data, dict) or not isinstance(data.get("web"), dict):
        raise StructureError(f"{source}: expected a top-level 'web' mapping")
    total = _count_leaves({k: v for k, v in data.items() if k != "_meta"})
    return total, _count_leaves(data["web"])


def parse_scenario_map(text: str, source: str) -> list[Scenario]:
    data = yaml.safe_load(text)
    rows = data.get("scenarios") if isinstance(data, dict) else None
    if not isinstance(rows, list) or not rows:
        raise StructureError(f"{source}: no 'scenarios' list")
    out: list[Scenario] = []
    for row in rows:
        if not (
            isinstance(row, dict)
            and isinstance(row.get("scenario"), str)
            and isinstance(row.get("status"), str)
            and "playwright_module" in row
        ):
            label = row.get("scenario", "?") if isinstance(row, dict) else "?"
            raise StructureError(f"{source}: row {label!r} lacks scenario/status/playwright_module")
        out.append(Scenario(row["scenario"], row["status"], row["playwright_module"]))
    return out


# ---------------------------------------------------------------------------
# Python facts (imported from the real modules)
# ---------------------------------------------------------------------------


def _use_root(root: Path) -> None:
    if str(root) not in sys.path:
        sys.path.insert(0, str(root))


def _read(root: Path, rel: str) -> str:
    return (root / rel).read_text(encoding="utf-8")


def _import_attr(module_name: str, attr: str, source: str) -> object:
    """Import a fact from a repo module. A failed import is a source error (exit 2), never exit 1."""
    try:
        module = importlib.import_module(module_name)
    except Exception as exc:  # any import-time failure (SyntaxError included) is a source defect
        raise StructureError(f"{source}: cannot import {module_name}: {exc}") from exc
    if not hasattr(module, attr):
        raise StructureError(f"{source}: {module_name} has no attribute {attr!r}")
    return getattr(module, attr)


def _review_decision_rows() -> list[tuple[str, str]]:
    VALID_DECISIONS = _import_attr(
        "core.app_service.review_service", "VALID_DECISIONS", "core/app_service/review_service.py"
    )
    if set(DECISION_MEANINGS) != set(VALID_DECISIONS):
        raise StructureError(
            "core/app_service/review_service.py: VALID_DECISIONS "
            f"{sorted(VALID_DECISIONS)} differs from the described values "
            f"{sorted(DECISION_MEANINGS)}; update DECISION_MEANINGS in gen_reference.py"
        )
    return [
        ("(empty)" if value == "" else f"`{value}`", meaning)
        for value, meaning in DECISION_MEANINGS.items()
    ]


def _settings_key_rows() -> list[tuple[str]]:
    keys = _import_attr("app.web.routes.settings", "_WEB_SETTINGS_KEYS", "app/web/routes/settings.py")
    if not keys:
        raise StructureError("app/web/routes/settings.py: _WEB_SETTINGS_KEYS is empty")
    return [(f"`{key}`",) for key in keys]


def _route_rows() -> list[tuple[str, str, str]]:
    create_app = _import_attr("app.web.main", "create_app", "app/web/main.py")
    with tempfile.TemporaryDirectory() as tmp:
        schema = create_app(frontend_dist=Path(tmp)).openapi()
    rows: list[tuple[str, str, str]] = []
    for path, item in schema.get("paths", {}).items():
        for method, operation in item.items():
            if method in HTTP_METHODS:
                rows.append((method.upper(), path, operation.get("summary") or "—"))
    if not rows:
        raise StructureError("create_app().openapi() lists no routes")
    return sorted(rows, key=lambda r: (r[1], HTTP_METHODS.index(r[0].lower())))


