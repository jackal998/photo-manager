"""Generate the code-derived reference tables in docs/reference/.

Usage:
    python scripts/gen_reference.py              # rewrite docs/reference/*.md
    python scripts/gen_reference.py --check      # exit 1 if a committed table is stale
    python scripts/gen_reference.py --root PATH  # read sources from another tree (scratch-copy probes)

Every table is built from the code, never typed by hand. Python facts come from
importing the real modules. TypeScript and scan-route facts come from STRICT
patterns that fail closed (StructureError) when a source no longer has the
shape the parser expects, so a partial table is never written.

Exit codes: 0 ok, 1 a committed table is stale (--check), 2 a source could not
be read, imported or parsed (the message names the file).
"""
from __future__ import annotations

import argparse
import ast
import importlib
import re
import sys
import tempfile
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

import yaml

REPO_ROOT = Path(__file__).resolve().parent.parent
REFERENCE_DIR = Path("docs") / "reference"
HEADER = "Generated by scripts/gen_reference.py — do not edit by hand."
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")
RESULT_COLUMNS_TS = "frontend/src/lib/resultColumns.ts"
TOOLBAR_SHED_TS = "frontend/src/lib/toolbarShed.ts"
SCAN_ROUTE_PY = "app/web/routes/scan.py"
SCENARIO_MAP_YML = "qa/web/scenario_map.yml"
TRANSLATIONS_DIR = "translations"

# Hand-written meaning per stored decision value. The keys must equal
# VALID_DECISIONS exactly; a new value is a StructureError until it is described here.
DECISION_MEANINGS = {
    "": "No decision: the row carries no mark",
    "delete": "Marked for delete",
    "ignore": "Marked ignore",
}
# What each shed toolbar constant hides. The keys must equal the constants parsed.
TOOLBAR_EFFECTS = {
    "TOOLBAR_MANIFEST_SHED_WIDTH": "Manifest path input and its Open button are hidden",
    "TOOLBAR_OVERFLOW_MENU_WIDTH": "Set Action, the language toggle and Settings fold into the overflow menu",
}


class StructureError(Exception):
    """A source no longer has the shape its parser expects. Fix the source or the parser."""


@dataclass(frozen=True)
class Column:
    id: str
    label: str
    label_key: str
    sortable: bool


@dataclass(frozen=True)
class ScanEvent:
    name: str
    terminal: bool
    emitted_by: str


@dataclass(frozen=True)
class Scenario:
    scenario: str
    status: str
    module: str | None


@dataclass(frozen=True)
class Table:
    filename: str
    title: str
    source: str
    intro: str
    headers: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]


def _lf(text: str) -> str:
    return text.replace("\r\n", "\n")


# ---------------------------------------------------------------------------
# TypeScript: result columns registry
# ---------------------------------------------------------------------------

_COLUMNS_BLOCK_RE = re.compile(
    r"^export const COLUMNS: readonly ColumnDef\[\] = \[\n(?P<body>.*?)\n\] as const;$",
    re.DOTALL | re.MULTILINE,
)
_UNION_RE = re.compile(
    r"^export type ColumnId =(?P<members>(?:\s*\|\s*\"\w+\")+)\s*;", re.MULTILINE
)
_COLUMN_ROW_RE = re.compile(
    r'^  \{ id: "(?P<id>\w+)", labelKey: "(?P<key>[^"]+)", labelFallback: "(?P<label>[^"]+)", '
    r"defaultWidth: \d+, sortable: (?P<sortable>true|false), "
    r'align: "(?:left|right)", mono: (?:true|false), flexible: (?:true|false) \},$'
)


def _is_data_line(line: str) -> bool:
    stripped = line.strip()
    return bool(stripped) and not stripped.startswith("//")


def _column_row(line: str, source: str) -> Column:
    match = _COLUMN_ROW_RE.match(line)
    if match is None:
        raise StructureError(
            f"{source}: COLUMNS row is not the registry literal shape: {line.strip()!r}"
        )
    return Column(match["id"], match["label"], match["key"], match["sortable"] == "true")


def parse_result_columns(text: str, source: str) -> list[Column]:
    text = _lf(text)
    block = _COLUMNS_BLOCK_RE.search(text)
    union = _UNION_RE.search(text)
    if block is None or union is None:
        raise StructureError(f"{source}: COLUMNS block or ColumnId union not in the expected shape")
    columns = [
        _column_row(line, source) for line in block["body"].split("\n") if _is_data_line(line)
    ]
    if not columns:
        raise StructureError(f"{source}: COLUMNS has no rows")
    ids = [c.id for c in columns]
    union_ids = re.findall(r'"(\w+)"', union["members"])
    if len(set(ids)) != len(ids) or set(ids) != set(union_ids):
        raise StructureError(
            f"{source}: ColumnId union {union_ids} does not match COLUMNS ids {ids}"
        )
    return columns


# ---------------------------------------------------------------------------
# TypeScript: toolbar shed constants
# ---------------------------------------------------------------------------


def parse_toolbar_shed(text: str, source: str) -> dict[str, int]:
    text = _lf(text)
    literals = {
        m[1]: int(m[2])
        for m in re.finditer(r"^export const (\w+) = (\d+);$", text, re.MULTILINE)
    }
    found = {m[1] for m in re.finditer(r"^export const (TOOLBAR_\w+_WIDTH)\b", text, re.MULTILINE)}
    if found != set(TOOLBAR_EFFECTS):
        raise StructureError(
            f"{source}: width constants {sorted(found)} differ from the described set "
            f"{sorted(TOOLBAR_EFFECTS)}; describe the new one in TOOLBAR_EFFECTS in gen_reference.py"
        )
    widths: dict[str, int] = {}
    for name in TOOLBAR_EFFECTS:
        match = re.search(rf"^export const {name} = (\w+);$", text, re.MULTILINE)
        if match is None:
            raise StructureError(
                f"{source}: {name} is not declared as 'export const {name} = <number or constant>;' "
                "(a typed or re-spaced declaration is refused, not skipped)"
            )
        value = match[1]
        if value.isdigit():
            widths[name] = int(value)
        elif value in literals:
            widths[name] = literals[value]
        else:
            raise StructureError(
                f"{source}: {name} = {value} is neither a literal nor a constant defined here"
            )
    return widths


# ---------------------------------------------------------------------------
# Python: scan SSE event names (AST, literal names only)
# ---------------------------------------------------------------------------


class _EmitVisitor(ast.NodeVisitor):
    def __init__(self, source: str) -> None:
        self.source = source
        self.events: list[ScanEvent] = []
        self._functions: list[str] = []

    def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
        self._functions.append(node.name)
        self.generic_visit(node)
        self._functions.pop()

    visit_AsyncFunctionDef = visit_FunctionDef  # type: ignore[assignment]

    def visit_Call(self, node: ast.Call) -> None:
        attr = node.func.attr if isinstance(node.func, ast.Attribute) else None
        if attr == "_append_and_fanout":
            self._add_literal(node, 0, terminal=False)
        elif attr == "_set_terminal":
            self._add_literal(node, 1, terminal=True)
        self.generic_visit(node)

    def visit_Dict(self, node: ast.Dict) -> None:
        for key, value in zip(node.keys, node.values):
            if (
                isinstance(key, ast.Constant)
                and key.value == "event"
                and isinstance(value, ast.Constant)
            ):
                self._record(str(value.value), terminal=False)
        self.generic_visit(node)

    def _add_literal(self, node: ast.Call, index: int, terminal: bool) -> None:
        arg = node.args[index] if len(node.args) > index else None
        if not (isinstance(arg, ast.Constant) and isinstance(arg.value, str)):
            raise StructureError(
                f"{self.source}:{node.lineno}: event name is not a string literal; "
                "the table cannot name it"
            )
        self._record(arg.value, terminal)

    def _record(self, name: str, terminal: bool) -> None:
        emitter = self._functions[-1] if self._functions else "<module>"
        self.events.append(ScanEvent(name, terminal, emitter))


def parse_scan_events(text: str, source: str) -> list[ScanEvent]:
    try:
        tree = ast.parse(text)
    except SyntaxError as exc:
        raise StructureError(f"{source}: {exc}") from exc
    visitor = _EmitVisitor(source)
    visitor.visit(tree)
    if not visitor.events:
        raise StructureError(f"{source}: no SSE event emission found")
    return sorted(set(visitor.events), key=lambda e: (e.name, e.emitted_by))


