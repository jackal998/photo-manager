def _columns_table(root: Path) -> Table:
    columns = parse_result_columns(_read(root, RESULT_COLUMNS_TS), RESULT_COLUMNS_TS)
    return Table(
        filename="columns.md",
        title="Result columns",
        source=f"`{RESULT_COLUMNS_TS}` (`COLUMNS`)",
        intro=(
            "Registry order is the left-to-right render order. `sortable` is whether a "
            "click on the header sorts by that column."
        ),
        headers=("id", "Label (English)", "Catalogue key", "Sortable"),
        rows=tuple(
            (f"`{c.id}`", c.label, f"`{c.label_key}`", "yes" if c.sortable else "no")
            for c in columns
        ),
    )


def _toolbar_table(root: Path) -> Table:
    widths = parse_toolbar_shed(_read(root, TOOLBAR_SHED_TS), TOOLBAR_SHED_TS)
    return Table(
        filename="toolbar-shed.md",
        title="Toolbar shed widths",
        source=f"`{TOOLBAR_SHED_TS}`",
        intro=(
            "Measured toolbar width (px) below which a control group is shed. A constant "
            "defined as another constant is shown with its resolved value."
        ),
        headers=("Constant", "Width (px)", "Effect below this width"),
        rows=tuple(
            (f"`{name}`", str(widths[name]), TOOLBAR_EFFECTS[name]) for name in TOOLBAR_EFFECTS
        ),
    )


def _settings_table() -> Table:
    return Table(
        filename="settings-keys.md",
        title="Web settings keys",
        source="`app/web/routes/settings.py` (`_WEB_SETTINGS_KEYS`)",
        intro=(
            "Keys the web settings route allowlists for both `GET /api/settings` and "
            "`PATCH /api/settings`. Any other key is not readable or writable through it."
        ),
        headers=("Key",),
        rows=tuple(_settings_key_rows()),
    )


def _routes_table() -> Table:
    return Table(
        filename="http-routes.md",
        title="HTTP routes",
        source="`create_app().openapi()` (`app/web/main.py`)",
        intro=(
            "Every operation in the OpenAPI document, sorted by path then method. Generated "
            "against an empty SPA directory, so the static mount is not listed."
        ),
        headers=("Method", "Path", "Summary"),
        rows=tuple(_route_rows()),
    )


def _sse_table(root: Path) -> Table:
    events = parse_scan_events(_read(root, SCAN_ROUTE_PY), SCAN_ROUTE_PY)
    return Table(
        filename="sse-events.md",
        title="Scan SSE events",
        source=f"`{SCAN_ROUTE_PY}` (literal event names)",
        intro=(
            "Event names the scan stream emits. A terminal event ends the stream. `ping` is "
            "the keepalive, sent by the stream generator with no id."
        ),
        headers=("Event", "Terminal", "Emitted by"),
        rows=tuple(
            (f"`{e.name}`", "yes" if e.terminal else "no", f"`{e.emitted_by}`") for e in events
        ),
    )


def _decisions_table() -> Table:
    return Table(
        filename="review-decisions.md",
        title="Review decision values",
        source="`core/app_service/review_service.py` (`VALID_DECISIONS`)",
        intro="Values the review service accepts as a stored decision. Any other value is rejected.",
        headers=("Stored value", "Meaning"),
        rows=tuple(_review_decision_rows()),
    )


def _i18n_table(root: Path) -> Table:
    rows: list[tuple[str, ...]] = []
    files = sorted((root / TRANSLATIONS_DIR).glob("*.yml"))
    if not files:
        raise StructureError(f"{TRANSLATIONS_DIR}/: no *.yml catalogues found")
    for path in files:
        total, web = count_i18n_keys(path.read_text(encoding="utf-8"), path.name)
        rows.append((f"`{path.stem}`", f"`{path.name}`", str(total), str(web)))
    return Table(
        filename="i18n-keys.md",
        title="i18n catalogue key counts",
        source=f"`{TRANSLATIONS_DIR}/*.yml`",
        intro=(
            "Leaf keys per catalogue: every scalar or list value, excluding `_meta`. "
            "`web.*` is the namespace the browser reads."
        ),
        headers=("Locale", "File", "Keys (total)", "Keys under `web.*`"),
        rows=tuple(rows),
    )


def _scenarios_table(root: Path) -> Table:
    scenarios = parse_scenario_map(_read(root, SCENARIO_MAP_YML), SCENARIO_MAP_YML)
    counts = Counter(s.status for s in scenarios)
    summary = ", ".join(f"{status} {n}" for status, n in sorted(counts.items()))
    return Table(
        filename="qa-scenarios.md",
        title="QA web scenarios",
        source=f"`{SCENARIO_MAP_YML}`",
        intro=f"{len(scenarios)} scenarios: {summary}.",
        headers=("Scenario", "Status", "Driver module"),
        rows=tuple(
            (f"`{s.scenario}`", s.status, f"`{s.module}`" if s.module else "—") for s in scenarios
        ),
    )


def _readme_table(tables: list[Table]) -> Table:
    return Table(
        filename="README.md",
        title="Reference tables",
        source="`scripts/gen_reference.py`",
        intro=(
            "Each table is regenerated from the code by `python scripts/gen_reference.py`. "
            "CI runs `--check` and fails when a committed table differs from a fresh run."
        ),
        headers=("Table", "Source", "Rows"),
        rows=tuple(
            (f"[{t.title}]({t.filename})", t.source, str(len(t.rows))) for t in tables
        ),
    )


def _tables(root: Path) -> list[Table]:
    _use_root(root)
    tables = [
        _columns_table(root),
        _toolbar_table(root),
        _settings_table(),
        _routes_table(),
        _sse_table(root),
        _decisions_table(),
        _i18n_table(root),
        _scenarios_table(root),
    ]
    return [*tables, _readme_table(tables)]


# ---------------------------------------------------------------------------
# Rendering, checking, writing
# ---------------------------------------------------------------------------


def render(table: Table) -> str:
    lines = [HEADER, "", f"# {table.title}", "", f"Source: {table.source}", ""]
    if table.intro:
        lines += [table.intro, ""]
    lines.append("| " + " | ".join(table.headers) + " |")
    lines.append("|" + "---|" * len(table.headers))
    for row in table.rows:
        for cell in row:
            if "|" in cell or "\n" in cell:
                raise StructureError(f"{table.filename}: cell {cell!r} would break the table")
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines) + "\n"


def build_tables(root: Path) -> dict[str, str]:
    """Filename -> full generated text for every reference table. Raises before writing anything."""
    return {table.filename: render(table) for table in _tables(root)}


def check_tables(expected: dict[str, str], docs_dir: Path) -> list[str]:
    problems: list[str] = []
    for name in sorted(expected):
        path = docs_dir / name
        if not path.is_file():
            problems.append(f"{name}: missing")
            continue
        committed = _lf(path.read_bytes().decode("utf-8"))
        if committed != expected[name]:
            problems.append(f"{name}: stale (hand-edited or out of date)")
    if docs_dir.is_dir():
        for path in sorted(docs_dir.glob("*.md")):
            if path.name not in expected:
                problems.append(f"{path.name}: orphaned (no table in gen_reference.py produces it)")
    return problems


def write_tables(expected: dict[str, str], docs_dir: Path) -> None:
    docs_dir.mkdir(parents=True, exist_ok=True)
    for name, text in expected.items():
        with open(docs_dir / name, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate docs/reference/*.md from the code.")
    parser.add_argument("--check", action="store_true", help="fail if a committed table is stale")
    parser.add_argument("--root", type=Path, default=REPO_ROOT, help="source tree to read")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        expected = build_tables(root)
    except (StructureError, OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        print(f"gen_reference: {exc}", file=sys.stderr)
        return 2
    docs_dir = root / REFERENCE_DIR
    if args.check:
        problems = check_tables(expected, docs_dir)
        if problems:
            print(f"reference tables out of date in {docs_dir}:")
            for problem in problems:
                print(f"  - {problem}")
            print(
                "fix: python scripts/gen_reference.py regenerates stale tables; it never deletes files, "
                "so delete any orphaned file listed above by hand"
            )
            return 1
        print(f"reference tables up to date ({len(expected)} files)")
        return 0
    write_tables(expected, docs_dir)
    print(f"wrote {len(expected)} reference files to {docs_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
